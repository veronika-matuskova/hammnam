-- Baseline: the `recipes` table as it existed in production on 2026-11-12,
-- before migrations were tracked. Written to be idempotent, so applying it to
-- the live project changes nothing and only records it in the migration history.

create table if not exists public.recipes (
  id               bigint generated by default as identity primary key,
  title_cs         text not null,
  title_sk         text not null,
  category_cs      text not null,
  category_sk      text not null,
  photo            text,
  sj               numeric,
  carbs            numeric,
  gi               text,
  favorite         boolean default false,
  ingredients_cs   jsonb,
  ingredients_sk   jsonb,
  instructions_cs  text,
  instructions_sk  text,
  created_at       timestamptz not null default timezone('utc'::text, now()),
  ingredients      jsonb default '[]'::jsonb,
  steps            jsonb default '[]'::jsonb,
  notes            text,
  servings         integer default 1,
  fiber            numeric default 0,
  calories         numeric default 0,
  proteins         numeric default 0,
  fats             numeric default 0,
  salt             numeric default 0,
  glycemic_load    numeric default 0
);

alter table public.recipes enable row level security;

-- Current behaviour: anyone with the publishable key can read and write.
do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'recipes'
      and policyname = 'Allow public access'
  ) then
    create policy "Allow public access" on public.recipes
      for all to public using (true) with check (true);
  end if;
end $$;
