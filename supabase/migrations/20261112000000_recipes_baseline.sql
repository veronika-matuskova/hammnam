alter table public.recipes add column if not exists favorite boolean not null default false;

-- -----------------------------------------------------------------------------
-- Row Level Security as it is today (before #5): the app reads and writes with
-- the publishable/anon key, so anonymous SELECT, INSERT and UPDATE must be
-- allowed. The app never deletes, so no DELETE policy is assumed.
-- The next migration (family write access) replaces these policies.
-- -----------------------------------------------------------------------------
alter table public.recipes enable row level security;

drop policy if exists "Public can read recipes" on public.recipes;
create policy "Public can read recipes"
  on public.recipes for select
  to anon, authenticated
  using (true);

drop policy if exists "Public can insert recipes" on public.recipes;
create policy "Public can insert recipes"
  on public.recipes for insert
  to anon, authenticated
  with check (true);

drop policy if exists "Public can update recipes" on public.recipes;
create policy "Public can update recipes"
  on public.recipes for update
  to anon, authenticated
  using (true)
  with check (true);

grant select, insert, update on public.recipes to anon, authenticated;
