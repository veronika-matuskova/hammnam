create table if not exists public.recipes (
  id bigint generated by default as identity primary key,
  title_cs text not null,
  title_sk text not null,
  category_cs text not null,
  category_sk text not null,
  photo text,
  -- Nutrition values per 100 g of the finished dish.
  sj numeric,
  carbs numeric,
  -- Glycemic index. Free text here; 20261112120000_recipes_gi_numeric.sql makes it numeric 0-100.
  gi text,
  favorite boolean default false,
  -- Legacy per-language columns, no longer read or written by the app.
  ingredients_cs jsonb,
  ingredients_sk jsonb,
  instructions_cs text,
  instructions_sk text,
  created_at timestamptz not null default timezone('utc'::text, now()),
  -- [{ "name": text, "amount": text, "unit": text }, ...]
  ingredients jsonb default '[]'::jsonb,
  -- [ "step text", ... ]
  steps jsonb default '[]'::jsonb,
  notes text,
  servings integer default 1,
  fiber numeric default 0,
  calories numeric default 0,
  proteins numeric default 0,
  fats numeric default 0,
  salt numeric default 0,
  glycemic_load numeric default 0
);

-- Row Level Security as it was: one policy letting anyone (including anonymous
-- visitors with the publishable key) read, insert, update AND delete.
-- 20261112230000_family_write_access.sql replaces it.
alter table public.recipes enable row level security;

drop policy if exists "Allow public access" on public.recipes;
create policy "Allow public access"
  on public.recipes for all
  to public
  using (true)
  with check (true);

grant all on public.recipes to anon, authenticated;
