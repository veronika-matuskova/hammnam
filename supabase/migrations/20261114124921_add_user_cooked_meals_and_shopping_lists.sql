-- =============================================================================
-- hamMňam: per-user cooked meals history and shopping lists
-- =============================================================================
--
-- Applied to the live project on 2026-11-14 (version 20261114124921) through
-- the Supabase connector; this file records it in the repository unchanged.
--
-- Each signed-in family member sees and manages only their own rows.
-- The app uses shopping_lists for the Nákupný zoznam view: one open list per
-- user (the newest row with completed_at NULL). cooked_meals is not used yet.
-- =============================================================================

-- History of meals a user cooked
create table public.cooked_meals (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  recipe_id bigint references public.recipes(id) on delete set null,
  recipe_title text not null,               -- snapshot, survives recipe edits/deletes
  servings integer not null default 1 check (servings > 0),
  note text,
  cooked_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);
comment on table public.cooked_meals is 'Per-user history of cooked meals.';
create index cooked_meals_user_cooked_at_idx on public.cooked_meals (user_id, cooked_at desc);
create index cooked_meals_recipe_id_idx on public.cooked_meals (recipe_id);

-- Saved shopping lists
create table public.shopping_lists (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  title text,
  recipe_ids bigint[] not null default '{}',  -- recipes the list was built from
  items jsonb not null default '[]'::jsonb,   -- [{name, amount, unit, checked}]
  created_at timestamptz not null default now(),
  completed_at timestamptz                    -- null = still open
);
comment on table public.shopping_lists is 'Per-user saved shopping lists. items: [{name, amount, unit, checked}].';
create index shopping_lists_user_created_at_idx on public.shopping_lists (user_id, created_at desc);

alter table public.cooked_meals enable row level security;
alter table public.shopping_lists enable row level security;

-- Each logged-in family member sees and manages only their own rows
create policy "Users manage own cooked meals" on public.cooked_meals
  for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()) and (select public.is_family_member()));

create policy "Users manage own shopping lists" on public.shopping_lists
  for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()) and (select public.is_family_member()));
